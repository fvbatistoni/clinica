A observação de que as células gonadotrópicas hipofisárias necessitam de estimulação pulsátil em vez de contínua pelo GnRH para manter a liberação contínua de gonadotropinas fornece a razão para a utilização de agonistas de GnRH para o tratamento de puberdade precoce central. Em virtude de serem mais potentes e com maior duração de ação do que o GnRH nativo, estes agonistas de GnRH (após um breve período de estimulação) “dessensibilizam” as células gonadotrópicas da hipófise contra o efeito estimulatório do GnRH endógeno e interrompem efetivamente a progressão da precocidade sexual central.</span></p>
