<p><b>A seguir falaremos de alguns dos marcadores tumorais
mais frequentemente utilizados:</b></p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Alfafetoproteína (AFP)</span></span><span style="font-weight: bold;"><span style="font-style: italic;"></span></span></p>
<p>A AFP pode ajudar a diagnosticar e orientar o
tratamento de câncer de fígado. Os níveis normais de AFP são geralmente menores
a 10 ng/ml. Os níveis da AFP estão aumentados na maioria dos pacientes com
câncer hepático. A AFP tamb&eacute;m pode estar elevada na hepatite aguda e crônica,
mas raramente acima de 100 ng/mL nestas doenças.</p>
<p>A AFP &eacute; útil no acompanhamento da resposta ao
tratamento do câncer de fígado. Se o tumor for completamente removido cirurgicamente,
o nível da AFP deve voltar a valores normais. Se o nível subir, pode significar uma recidiva
da doença.</p>
<p>A AFP tamb&eacute;m &eacute; maior em determinados tumores
de c&eacute;lulas germinativas, como alguns tipos de câncer de testículo, certos tipos
raros de câncer de ovário e os tumores de c&eacute;lulas germinativas que se originam na
região torácica.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Quinase do Linfoma Anaplásico (ALK)</span></span><span style="font-weight: bold;"><span style="font-style: italic;"></span></span></p>
<p>Alguns cânceres de pulmão têm alterações no
gene ALK que induz as c&eacute;lulas cancerígenas a produzirem uma proteína que provoca
o crescimento fora de controle. Os tecidos tumorais podem ser estudados para
alterações desse gene.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">BCR-ABL</span></span><span style="font-weight: bold;"><span style="font-style: italic;"></span></span></p>
<p>As c&eacute;lulas da leucemia mieloide crônica (LMC)
cont&eacute;m um gene anormal denominado BCR-ABL. O exame de PCR pode detectar este
gene em quantidades muito pequenas no sangue ou na medula óssea. Em pessoas com
alterações no sangue e medula óssea que se parecem com as observadas na LMC, encontrar
o gene confirma o diagnóstico. Al&eacute;m disso, o achado do gene e seu valor podem
ser medidos e usados para guiar o tratamento.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Beta-2-Microglobulina (B2M)</span></span></p>
<p>Os níveis sanguíneos do B2M estão elevados no
mieloma múltiplo, leucemia linfóide crônica e alguns linfomas, incluindo Macroglobulinemia
de Waldenström. Esses níveis tamb&eacute;m podem estar elevados em outras condições, como
em doenças renais e a hepatite. O B2M &eacute; útil no prognóstico a longo prazo em
alguns desses tipos de câncer. O B2M tamb&eacute;m &eacute; verificado durante o tratamento
do mieloma múltiplo e da Macroglobulinemia de Waldenström para avaliar a
resposta terapêutica.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Antígeno Tumoral da Bexiga (BTA)</span></span></p>
<p>O BTA &eacute; encontrado na urina de muitos
pacientes com câncer de bexiga. Pode aparecer como a manifestação de algumas
condições não cancerígenas, como cálculos renais ou infecções do trato
urinário. Às vezes &eacute; usado junto com NMP22 para determinar a recidiva do câncer
de bexiga.</p>
<p>Este exame não &eacute; realizado com frequência.
Não &eacute; tão eficaz quanto a cistoscopia para detectar o câncer de bexiga, mas
pode ser útil por permitir que a cistoscopia seja realizada com menos
frequência durante o acompanhamento do câncer de bexiga. No momento, a maioria
dos especialistas ainda considera a cistoscopia a melhor maneira de
diagnosticar e acompanhar a doença. </p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">BRAF</span></span></p>
<p>Mutações no gene BRAF podem ser encontradas no
melanoma, no câncer de tireoide e no câncer colorretal. Cerca da metade dos
melanomas têm uma mutação BRAF, na maioria das vezes o chamado BRAF V600. Esta
mutação faz com que o gene produza uma proteína BRAF alterada, que sinaliza as
c&eacute;lulas de melanoma para crescerem e se dividirem. Esta mutação pode ser estudada
no tecido tumoral.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">CA 15-3</span></span></p>
<p>O marcador tumoral CA 15-3 &eacute; usado
principalmente em pacientes com câncer de mama. Níveis sanguíneos elevados são
encontrados em cerca de 10% dos pacientes com doença inicial e em cerca de 70%
dos pacientes com doença avançada.</p>
<p>O valor normal &eacute; geralmente inferior a 30
U/ml, dependendo do laboratório. Mas, valores da ordem de 100 U/mL podem ser
observados em mulheres que não têm câncer. Níveis deste marcador tamb&eacute;m podem estar
elevados em outros tipos de câncer, como o de pulmão, cólon, pâncreas e ovário.
</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">CA 19-9</span></span></p>
<p>O marcador tumoral CA 19-9 foi desenvolvido
para a detecção do câncer colorretal, mas &eacute; mais frequentemente usado em pacientes
com câncer de pâncreas. Na doença inicial, o nível pode ser normal, por isso
não &eacute; um bom marcador para triagem. Ainda assim, &eacute; o melhor marcador tumoral
para acompanhamento de pacientes com câncer de pâncreas.</p>
<p>O CA 19-9 pode estar aumentado em outros tipos
de câncer do trato digestivo, como no câncer de estômago e de vias biliares, e,
em algumas condições benignas, como doenças da tireoide, artrite reumatoide,
doença inflamatória intestinal e pancreatite.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">CA 27-29</span></span></p>
<p>O CA 27-29 &eacute; outro marcador que pode ser
utilizado para o acompanhamento de pacientes com câncer de mama, durante ou
após o tratamento. Embora seja um exame mais moderno que o CA 15-3, não &eacute; superior
na detecção da doença inicial ou avançada. E não se encontra aumentado em todas
as pacientes com câncer de mama.</p>
<p>Os valores normais geralmente são inferiores a
40 U/ml, dependendo do laboratório. Este marcador pode estar aumentado em
outros tipos de câncer, como câncer do cólon, estômago, rim, pulmão, ovário,
pâncreas, útero e fígado. Ele tamb&eacute;m pode estar elevado em algumas condições benignas,
por exemplo, em mulheres durante o primeiro trimestre de gravidez e em pessoas
com endometriose, cistos ovarianos, doença benigna da mama, cálculos renais e
doenças hepáticas.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">CA 125</span></span></p>
<p>CA 125 &eacute; o marcador tumoral padrão usado para
acompanhar as mulheres durante ou após o tratamento do câncer epitelial de
ovário.</p>
<p>Os níveis sanguíneos normais são normalmente inferiores
a 35 U/ml. Mais de 90% das mulheres com câncer de ovário avançado apresentam altos
níveis de CA 125.</p>
<p>Os níveis desse marcador tamb&eacute;m podem ser elevados
em homens e mulheres com câncer de pulmão, pâncreas, mama, fígado e cólon, e em
pessoas que já tiveram câncer. </p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Calcitonina</span></span></p>
<p>A calcitonina &eacute; um hormônio produzido pelas
c&eacute;lulas parafoliculares C da glândula tireoide, que normalmente ajuda a regular
os níveis de cálcio no sangue. Os valores de calcitonina normais devem estar abaixo
5 a 12 pg/mL. No carcinoma medular da tireoide (MTC), um tipo raro de câncer
que começa nas c&eacute;lulas parafoliculares C, os níveis sanguíneos deste hormônio
são frequentemente superiores a 100 pg/ml.</p>
<p>Este &eacute; um dos marcadores tumorais raros, que
pode ser usado &#8203;&#8203;para ajudar a detectar o câncer precocemente. Como o MTC &eacute;
muitas vezes herdado, a calcitonina no sangue pode ser medida para detectar o
câncer em estágio inicial em membros da família que se sabe estar em risco.</p>
<p>Outros tipos de câncer, como o de pulmão e
leucemias, tamb&eacute;m pode elevar os níveis da calcitonina, mas os exames de sangue
para determinar a presença de calcitonina não são normalmente usados &#8203;&#8203;para
detectar esses tipos de câncer.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Antígeno Carcinoembrionário (CEA)</span></span></p>
<p>O CEA não &eacute; usado para diagnosticar ou
detectar o câncer de intestino, mas &eacute; o marcador de tumor preferido para ajudar
a prever o prognóstico em pacientes com câncer colorretal.</p>
<p>Os valores normais variam de laboratório para
laboratório, e os fumantes costumam ter níveis mais altos. Mas, mesmo em tabagistas,
valores maiores do que 5,5 ng/ml não são normais. Quanto maior o valor de CEA
no momento do diagnóstico significa probabilidade de doença avançada.</p>
<p>O CEA &eacute; tamb&eacute;m o marcador padrão utilizado
para o acompanhamento de pacientes com câncer colorretal, durante e após o
tratamento. Desta forma, os níveis de CEA são utilizados para monitorar a
resposta terapêutica e detecção precoce de uma recidiva após o tratamento.</p>
<p>O CEA pode ser usado para câncer de pulmão e de
mama. Este marcador pode tamb&eacute;m estar alterado em outros tipos de câncer, como
melanoma, linfoma, tireoide, pâncreas, fígado, estômago, rim, próstata, ovário,
colo do útero e bexiga. &Eacute; importante mencionar que pode estar elevado em
algumas doenças benignas, como hepatite, doença pulmonar obstrutiva crônica,
colite, artrite reumatoide e pancreatite.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Cromogranina A</span></span></p>
<p>A cromogranina A (CgA) &eacute; produzida por
tumores neuroendócrinos, que incluem tumores carcinoides, neuroblastoma e
câncer de pulmão de pequenas c&eacute;lulas. Os valores de CgA estão muitas vezes aumentados
em pacientes com essas doenças.</p>
<p>&Eacute;, provavelmente, o marcador tumoral mais
sensível para os tumores carcinoides. Está alterado em 1 de cada 3 pacientes com
doença localizada e em 2 de cada 3 pacientes com doença metastática. Os níveis desse
marcador tamb&eacute;m podem estar elevados em algumas formas avançadas do câncer de
próstata com características neuroendócrinas. &Eacute; difícil definir o valor normal
para CgA porque há diferentes maneiras de medir este marcador e cada um tem o
seu próprio parâmetro.</p>
<p>Tomar medicamentos inibidores da bomba de
prótons, como omeprazol e lansoprazol, pode aumentar os níveis de CgA em
pessoas saudáveis, por isso seu m&eacute;dico deve ser informado do uso desses medicamentos
antes de você realizar esse exame.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Receptor do Fator de Crescimento Epid&eacute;rmico
(EGFR)</span></span></p>
<p>Esta proteína, tamb&eacute;m conhecida como HER1, &eacute; um
receptor que ajuda no crescimento celular. O EGFR pode ser utilizado para guiar
o tratamento e prever os resultados do câncer de pulmão de não pequenas c&eacute;lulas,
câncer de cabeça e pescoço, câncer colorretal, câncer do pâncreas ou do câncer
de mama.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">HE-4</span></span></p>
<p>Alguns tipos de câncer de ovário manifestam o
gene HE-4, produzindo quantidades maiores da proteína HE-4. Os níveis dessa
proteína são medidos no sangue e utilizados da mesma forma que o CA-125 para
orientar o tratamento. Este exame &eacute; mais frequentemente usado em pacientes com níveis
normais de CA 125. Os valores de HE-4 podem tamb&eacute;m aumentar em algumas
condições benignas, bem como com alguns outros tipos de câncer, por isso não &eacute;
usado como teste de triagem.</p>
<p><span lang="EN-US"></span><span style="font-weight: bold;"><span style="font-style: italic;" lang="EN-US">HER2 (HER2/neu,erbB-2 ou EGFR2)</span></span></p>
<p>HER2 &eacute; uma proteína que induz algumas c&eacute;lulas
cancerígenas a crescer. Ela está presente em quantidade maior do que o normal
na superfície de c&eacute;lulas cancerígenas em 1 em cada 5 pacientes com câncer de
mama. Níveis superiores aos normais tamb&eacute;m podem ser encontrados no câncer de estômago
e esôfago. Os tumores HER2-positivos tendem a crescer e se espalharem mais
rapidamente do que outros tipos de câncer.</p>
<p>Todos os cânceres de mama diagnosticados e
cânceres avançados do estômago devem ser investigados para HER2. Os tumores HER2-positivos
responderem a medicamentos que agem contra o receptor HER2. </p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Receptores Hormonais</span></span></p>
<p>As amostras de tumores de mama - não amostras
de sangue - de todos os pacientes com câncer de mama (mulheres e homens) são investigadas
para receptores de estrogênio e progesterona. Os cânceres de mama que contêm
receptores de estrogênio são denominados ER-positivo, e os com receptores de
progesterona são PR-positivo. Tumores com esses receptores hormonais positivos
tendem a crescer mais lentamente e podem ter um melhor prognóstico.</p>
<p>Alguns tumores ginecológicos, como os cânceres
de endom&eacute;trio e sarcomas do estroma endometrial, tamb&eacute;m são investigados para
os receptores hormonais.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Gonadotrofina Coriônica Humana (HCG)</span></span></p>
<p>Os níveis de HCG ou beta-HCG ou &#946;-HCG no
sangue estão aumentados em pacientes com alguns tipos de câncer de testículo e
ovário (tumores de c&eacute;lulas germinativas) e doença trofoblástica gestacional,
principalmente coriocarcinoma. Eles tamb&eacute;m estão aumentados em alguns pacientes
com tumores de c&eacute;lulas germinativas do mediastino. Os níveis de HCG podem ser
usados no diagnóstico, para monitorar a resposta ao tratamento e para detectar
precocemente uma recidiva.</p>
<p>&Eacute; difícil definir o valor normal HCG porque existem
diferentes maneiras de avaliar este marcador e cada um tem o seu próprio parâmetro.
</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Imunoglobulinas</span></span></p>
<p>As imunoglobulinas não são marcadores
tumorais clássicos, são anticorpos, constituídos de proteína, normalmente produzidas
por c&eacute;lulas do sistema imunológico para ajudar a combater infecções. Existem
muitos tipos de imunoglobulinas, incluindo IgA, IgG, IgD e IgM. Os cânceres da
medula óssea, como mieloma múltiplo e Macroglobulinemia de Waldenström, mostram
aumento de um tipo de imunoglobulina no sangue. Um valor aumentado de
imunoglobulinas pode ser um sinal de uma dessas doenças. Isto pode ser verificado
no exame eletroforese de proteínas. No entanto, o diagnóstico do mieloma
múltiplo ou da Macroglobulinemia de Waldenström, deve ser confirmado por
biópsia da medula óssea.</p>
<p>Os níveis da imunoglobulina tamb&eacute;m podem ser acompanhados
ao longo do tempo para monitorar a resposta terapêutica.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Cadeias Leves Livres</span></span></p>
<p>As imunoglobulinas são compostas de cadeias
de proteínas: duas cadeias longas cadeias (pesadas) e 2 cadeias curtas (leves).
Às vezes, no mieloma múltiplo uma proteína M não pode ser encontrada, mas o
nível da parte da cadeia leve no sangue está elevado. Este valor pode ser medido
com o exame cadeias leves e pode ser usado para ajudar a orientar o tratamento.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">KRAS</span></span></p>
<p>O cetuximabe e o panitumumabe são dois medicamentos
que têm como alvo a proteína EGFR, e podem ser úteis no tratamento do câncer colorretal
avançado. Mas esses medicamentos não atuam eficazmente no tratamento do câncer
colorretal com mutações no gene KRAS. Por essa razão, os pacientes devem ser estudados
para verificar se tem mutação nesse gene antes de iniciar o tratamento.</p>
<p>Mutações KRAS tamb&eacute;m podem ajudar a orientar
o tratamento para alguns tipos de câncer de pulmão. Por exemplo, em tumores em que
as mutações não respondem ao tratamento com erlotinibe ou gefitinibe. Os pesquisadores
estão estudando como o gene KRAS pode ser usado em outros tipos de câncer.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Desidrogenase Lática (LDH)</span></span></p>
<p>O LDH &eacute; utilizado como marcador tumoral para
o câncer de testículo e outros tumores de c&eacute;lulas germinativas. Não &eacute; tão útil
como o AFP e o HCG para o diagnóstico, pois se eleva com muitas outras condições
al&eacute;m do câncer, incluindo problemas no sangue e fígado. Ainda assim, os níveis aumentados
de LDH não mostram um bom prognóstico de sobrevida. Os níveis de LDH, tamb&eacute;m
são utilizados para monitorar a resposta ao tratamento e a detecção de uma
recidiva.</p>
<p>O LDH pode ser usado tamb&eacute;m em outros tipos
de câncer, como linfoma, melanoma e neuroblastoma.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Enolase Neurônio Específa (NSE)</span></span></p>
<p>O NSE, assim como a cromogranina A, &eacute; um
marcador de tumores neuroendócrinos, como o câncer de pulmão de pequenas c&eacute;lulas,
neuroblastoma e tumor carcinoide.</p>
<p>&Eacute; um marcador útil no acompanhamento de
pacientes com esses tipos de câncer. Níveis elevados de NSE tamb&eacute;m podem ser encontrados
no câncer medular da tireoide, melanoma e tumores endócrinos pancreáticos.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">NMP22</span></span></p>
<p>O NMP22 &eacute; uma proteína encontrada no núcleo
das c&eacute;lulas. Os níveis de NMP22 estão frequentemente elevados na urina de pacientes
com câncer de bexiga.</p>
<p>Este exame não &eacute; amplamente utilizado
atualmente, uma vez que ainda não &eacute; considerado sensível o suficiente para ser
usado como ferramenta de triagem. &Eacute; mais frequentemente utilizado para detectar
recidivas do câncer de bexiga após o tratamento. Seus níveis tamb&eacute;m podem estar
elevados em algumas condições benignas ou em pacientes que fizeram tratamento
quimioterápico recentemente.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Antígeno Prostático Específico (PSA)</span></span></p>
<p>O PSA &eacute; um marcador tumoral para o câncer de
próstata. O PSA &eacute; uma proteína produzida pelas c&eacute;lulas da glândula prostática,
&eacute; encontrada apenas em homens.</p>
<p>O nível de PSA no sangue pode estar elevado
no câncer de próstata, mas tamb&eacute;m pode ser afetado por outras razões. Homens
com hiperplasia prostática benigna, um crescimento benigno da próstata,
frequentemente têm níveis mais elevados. O nível de PSA tamb&eacute;m tende a ser
maior em homens mais velhos e aqueles com próstatas infeccionadas ou inflamadas.
Ele tamb&eacute;m pode estar elevado um dia ou dois após a ejaculação.</p>
<p>O PSA &eacute; importante no monitoramento da
resposta terapêutica e no acompanhamento de homens com câncer de próstata. Nos
homens tratados cirurgicamente com objetivo de cura, o PSA deve cair para um
nível indetectável. O PSA tamb&eacute;m deve cair após o tratamento radioterápico. Um
aumento no nível do PSA pode ser sinal de recidiva.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Fosfatase Ácida Prostática (PAP)</span></span></p>
<p>O PAP foi o primeiro
marcador tumoral usado no câncer de próstata. Este marcador possui limitações,
pois costuma se apresentar elevado apenas nos estágios mais avançados da
doença, não sendo por isso, de muita utilidade nos estágios iniciais. Após o
surgimento do PSA como marcador para o câncer de próstata, o PAP caiu em
desuso.</p>
<p>O PAP tamb&eacute;m pode ser usado para ajudar no
diagnóstico do mieloma múltiplo e o câncer de pulmão.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">S-100</span></span></p>
<p>S-100 &eacute; uma proteína encontrada na maioria
das c&eacute;lulas de melanoma. As amostras suspeitas de tecidos podem ser analisadas por
este marcador para ajudar no diagnóstico.<span style="font-weight: bold;"></span></p>
<p>Alguns estudos demonstraram que os níveis
sanguíneos de S-100 estão elevados na maioria dos pacientes com melanoma
metastático. Assim, este exame &eacute; às vezes realizado para verificar disseminação
da doença antes, durante ou após o tratamento.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Peptídeos Solúveis relacionados a Mesotelina (SMRP)</span></span></p>
<p>Este exame &eacute; muitas vezes usado em conjunto
com exames de imagem para diagnosticar o mesotelioma. Tamb&eacute;m pode ser realizado
para verificar uma recidiva após o tratamento.</p>
<p>Os pesquisadores estão avaliando se o SMRP
pode ser usado como uma ferramenta de rastreamento em pessoas com alto risco
para o mesotelioma.</p>
<p><span style="font-weight: bold;"><span style="font-style: italic;">Tireoglobulina</span></span></p>
<p>A tireoglobulina &eacute; uma proteína produzida
pela glândula tireoide. Os níveis sanguíneos normais dependem da idade e sexo
da pessoa. Os níveis da tireoglobulina se apresentam elevados em muitas doenças
da tireoide, incluindo algumas formas comuns de câncer da tireoide.</p>
<p>Os níveis de tireoglobulina no sangue devem
cair para níveis indetectáveis após o tratamento de um câncer da tireoide. Um aumento
no nível da tireoglobulina após o tratamento pode significar uma recidiva.</p>
<p>
O sistema imunológico de algumas pessoas produzem
anticorpos contra a tireoglobulina, que podem afetar os resultados deste exame.
Devido a isso, os níveis de anticorpos antitiroglobulina são frequentemente investigados
simultaneamente.</p>

