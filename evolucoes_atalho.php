<section id="s0945" class="calibre2"><h3 id="st0940" class="h2hd">HipoParatireoidismo</h3><div id="p4445" class="textfl">A concentração sérica de cálcio é baixa (5-7 mg/dL), enquanto a concentração de fósforo está elevada (7-12 mg/dL). As concentrações sanguíneas de cálcio ionizado (aproximadamente 45% do total) refletem mais precisamente a adequação fisiológica, porém também estão baixas. O valor sérico da fosfatase alcalina apresenta-se normal ou baixo, e o valor de 1,25(OH)<sub class="calibre10">2</sub>D<sub class="calibre10">3</sub> está habitualmente diminuído; todavia, foram observados valores elevados em algumas crianças com hipocalcemia grave. O valor de magnésio está normal, porém sempre deve ser avaliado em pacientes hipocalcêmicos. As concentrações de PTH estão baixas quando medidas por ensaio imunométrico. Em certas ocasiões, as radiografias dos ossos revelam aumento da densidade limitada às metáfises, sugerindo intoxicação por metais pesados ou densidade aumentada da lâmina dura. As radiografias ou a TC do crânio podem revelar calcificações nos núcleos da base. Observa-se prolongamento do intervalo QT no eletrocardiograma, que desaparece com a correção da hipocalcemia. Em geral, o eletroencefalograma revela atividade lenta generalizada; o traçado normaliza-se quando a concentração sérica de cálcio retorna à faixa normal durante algumas semanas, a não ser que tenha ocorrido lesão cerebral irreversível, ou a não ser que a insuficiência da paratireoide esteja associada a epilepsia. Quando o hipoparatireoidismo ocorre simultaneamente com a doença de Addison, a concentração sérica de cálcio pode estar normal, porém surge hipocalcemia após o tratamento eficaz da insuficiência adrenal.</div>
<div>A <b>NEM tipo I</b> é um distúrbio autossômico dominante, caracterizado por hiperplasia ou neoplasia do pâncreas endócrino (que secreta gastrina, insulina, polipeptídio pancreático e, em certas ocasiões, glucagon), da adeno-hipófise (que habitualmente secreta prolactina) e das glândulas paratireoides. Na maioria das famílias, o hiperparatireoidismo costuma ser a manifestação de apresentação, com uma prevalência que se aproxima de 100% em torno dos 50 anos de idade, mas que ocorre apenas raramente em crianças antes dos 18 anos. Com o uso de sondas de DNA apropriadas, é possível detectar portadores do gene com uma acurácia de 99% ao nascimento, evitando, assim, programas de triagem bioquímica desnecessários.
O gene da NEM tipo I está localizado no cromossomo 11q13; parece funcionar como um gene supressor tumoral e segue a hipótese de duas lesões para o desenvolvimento de tumores.</div><div>A NEM2A é um distúrbio autossômico dominante, que se caracteriza por CMT, feocromocitoma e hiperplasia das paratireoides. Pelo menos 19 mutações missense dos éxons 10 ou 11 do domínio extracelular do gene RET foram descritas para a NEM2A e para casos de CMT familiar.</div><div>A NEM2B é um distúrbio autossômico dominante, caracterizado por CMT e feocromocitoma, porém sem hiperparatireoidismo. A característica distintiva da NEM2B, também conhecida como síndrome de neuromas mucosos, consiste na ocorrência de múltiplos neuromas e fenótipo característico, que inclui fácies Marfan-like. </div>
