<p class="c0"><span class="c2 c5 c3"><b>PUBERDADE PRECOCE</b></span><br>
<span class="c2">A administração intravenosa de hormônio liberador de gonadotropinas (teste de estímulo com GnRH) ou um agonista de GnRH (teste de estímulo com leuprolida) é uma ferramenta diagnóstica útil, particularmente para meninos, nos quais uma resposta “púbere” de LH (pico de LH &gt; 5 unidades internacionais/litro) com predominância de LH sobre o hormônio folículo-estimulante (FSH) tende a ocorrer precocemente durante o curso da puberdade precoce. Em meninas com precocidade sexual, entretanto, a secreção noturna de LH e a resposta do LH ao GnRH ou ao agonista de GnRH pode ser bastante baixa nos estágios mamários iniciais II a III (pico de LH imunométrico &lt; 5 unidades internacionais/litro), e a relação LH:FSH pode permanecer baixa até o meio da puberdade. Nestas meninas com “baixa” resposta do LH, a natureza central da precocidade sexual pode ser comprovada pela detecção de níveis púberes de estradiol (&gt; 50 pg/mL), 20 a 24 horas após o estímulo com leuprolida.<br>
